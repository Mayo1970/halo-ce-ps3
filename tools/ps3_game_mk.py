#!/usr/bin/env python3
"""Writes the make rules of the game's units (port/linux/port.json) for the PS3 Makefile.
Make cannot list paths with spaces ("source/saved films"), so each unit gets an explicit rule."""

import argparse
import json
from pathlib import Path


def make_escape(path: str) -> str:
    return path.replace(" ", "\\ ")


def shell_quote(argument: str) -> str:
    return f'"{argument}"' if " " in argument else argument


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--build", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    config = json.loads(args.config.read_text(encoding="utf-8"))
    game = config["game"]
    excluded = set(game.get("exclude", []))
    sources = sorted(
        path.as_posix() for path in Path(game["root"]).rglob("*.c") if path.as_posix() not in excluded
    )
    sources += sorted(path.as_posix() for path in Path(config["game_sources"]).glob("*.c"))

    lines = [
        "# generated by tools/ps3_game_mk.py - do not edit",
        "GAME_DEFINES := " + " ".join(f"-D{define}" for define in game.get("defines", [])),
        "GAME_INCLUDES := " + " ".join(shell_quote(f"-I{directory}") for directory in game.get("include_dirs", [])),
        "GAME_OBJS :=",
    ]
    rules = []
    for source in sources:
        obj = f"{args.build}/obj/{Path(source).with_suffix('.o').as_posix().replace(' ', '_')}"
        lines.append(f"GAME_OBJS += {obj}")
        rules += [f"{obj}: {make_escape(source)}", "\t$(game_compile)", ""]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines + [""] + rules)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
        args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
