#!/usr/bin/env python3
"""Writes the make rules of the game's units (the game's port/linux/port.json) for the PS3 Makefile.
Make cannot list paths with spaces ("source/saved films"), so each unit gets an explicit rule.
Each unit is compiled from its rewritten copy in the LP64 folder (tools/ps3_lp64_tree.py)."""

import argparse
import json
from pathlib import Path


def make_escape(path: str) -> str:
    return path.replace(" ", "\\ ")


def shell_quote(argument: str) -> str:
    return f'"{argument}"' if " " in argument else argument


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--game", type=Path, required=True)
    parser.add_argument("--lp64", required=True)
    parser.add_argument("--build", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    config = json.loads((args.game / "port/linux/port.json").read_text(encoding="utf-8"))
    game = config["game"]
    # (the 64-bit builds' exclusions too: libtiff)
    excluded = game.get("exclude", []) + config.get("lp64", {}).get("exclude", [])

    def listed(paths):
        names = (path.relative_to(args.game).as_posix() for path in paths)
        # a name ending in "/" excludes a folder (the game's tools/linux_build.py's game_sources)
        return sorted(name for name in names
                      if not any(name == item or (item.endswith("/") and name.startswith(item)) for item in excluded))

    sources = listed((args.game / game["root"]).rglob("*.c"))
    sources += listed((args.game / config["game_sources"]).glob("*.c"))
    # the consoles' shared game code: the maps' byte order
    sources += listed((args.game / "port/console/game").glob("*.c"))
    # ours (port/ps3/game: the ONLINE GAMES screen), from the repository's root as the LP64 copy has them
    sources += sorted(path.as_posix() for path in Path("port/ps3/game").glob("*.c"))

    includes = [shell_quote(f"-I{args.lp64}/{directory}") for directory in game.get("include_dirs", [])]
    # (the originals after the copies, for what is not rewritten: port/third_party/stb)
    includes += ["-idirafter " + shell_quote(f"{args.game.as_posix()}/{directory}")
                 for directory in game.get("include_dirs", [])]
    lines = [
        "# generated by tools/ps3_game_mk.py - do not edit",
        "GAME_DEFINES := " + " ".join(f"-D{define}" for define in game.get("defines", [])),
        "GAME_INCLUDES := " + " ".join(includes),
        "GAME_OBJS :=",
    ]
    rules = []
    for source in sources:
        obj = f"{args.build}/obj/{Path(source).with_suffix('.o').as_posix().replace(' ', '_')}"
        lines.append(f"GAME_OBJS += {obj}")
        rules += [f"{obj}: {make_escape(f'{args.lp64}/{source}')}", "\t$(game_compile)", ""]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines + [""] + rules)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
        args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
